  // ─── Helper ──────────────────────────────────────────────────────────────────

  static SyllabusChapter _ch(
    String id,
    String title,
    List<String> topicPairs,
  ) {
    final topics = <SyllabusTopic>[];
    for (var i = 0; i + 1 < topicPairs.length; i += 2) {
      topics.add(SyllabusTopic(id: topicPairs[i], title: topicPairs[i + 1]));
    }
    return SyllabusChapter(
      id: id,
      title: 'Ch ${id.substring(2).padLeft(2, '0')} — $title',
      topics: topics,
    );
  }
